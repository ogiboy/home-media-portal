import * as React from 'react';
import { Command as CommandPrimitive } from 'cmdk';
import { Search } from 'lucide-react';

import { cn } from '@/lib/utils';
import { Dialog, DialogContent } from '@/components/ui/dialog';

const Command = React.forwardRef<
  React.ElementRef<typeof CommandPrimitive>,
  React.ComponentPropsWithoutRef<typeof CommandPrimitive>
>(({ className, ...props }, ref) => (
  <CommandPrimitive
    ref={ref}
    className={cn(
      'flex h-full w-full flex-col overflow-hidden rounded-(--radius) bg-card text-foreground',
      className
    )}
    {...props}
  />
));
Command.displayName = CommandPrimitive.displayName;

type CommandDialogProps = React.ComponentPropsWithoutRef<typeof Dialog> & {
  closeLabel?: string;
};

const CommandDialog = ({
  children,
  closeLabel,
  ...props
}: CommandDialogProps) => (
  <Dialog {...props}>
    <DialogContent
      className="overflow-hidden p-0 shadow-2xl"
      closeLabel={closeLabel}
    >
      <Command className="border-0">{children}</Command>
    </DialogContent>
  </Dialog>
);

